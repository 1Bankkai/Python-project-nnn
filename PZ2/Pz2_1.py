n = input('Введите 3-х значное число -')
try:
    n = int(n)   #Проверка на число тру
except ValueError:
    print('Вы ввели не число!')

if n>=100 and n<1000: #Проверка на 3-х значное число
    a = n%100
    b = n//100
    d = a*10 + b
    print(d)
else:
    print('Вы ввели не 3-х значное число')